"""PIT-012: optional settlement traces must never change outcome or money."""
from dataclasses import replace
from datetime import UTC, datetime

import pytest
from test_official_settlement import DisqualifiedClient, ResultsClient, ticket
from test_shadow_ledger import _store

from hbi.nightly import settle_open_shadow_tickets
from hbi.settlement_trace import PrivateAttemptJournal, PrivateTraceRejected, verify_trace


class PublicClient(ResultsClient):
    def raceday_results(self, *args):
        return replace(
            super().raceday_results(*args),
            url="https://www.rikstoto.no/api/results/racedays/BJ_NR_2026-09-27/raceresults",
        )

    def complete_results(self, *args):
        return replace(
            super().complete_results(*args),
            url="https://www.rikstoto.no/api/results/raceDays/BJ_NR_2026-09-27/1/completeresults",
        )


def run(tmp_path, client, observer=None, selection="2"):
    store = _store(tmp_path)
    ticket(store, selection)
    before = store.fetch_table("shadow_tickets")[0].copy()
    result = settle_open_shadow_tickets(
        store, client=client, trace_hook=observer,
        settled_at=datetime(2026, 9, 28, tzinfo=UTC),
    )
    return store, before, result, store.fetch_table("shadow_tickets")[0]


@pytest.mark.parametrize("attribute,value,expected_reason", [
    (None, None, "SETTLED"),
    ("finish", 0, "RESULT_CODE_UNSUPPORTED"),
    ("complete", False, "OFFICIAL_RESULT_INCOMPLETE"),
    ("payout_status", "Pending", "WINNING_DIVIDEND_MISSING_OR_UNCONFIRMED"),
])
def test_tracing_preserves_status_stake_and_pnl(tmp_path, attribute, value, expected_reason):
    client1, client2 = ResultsClient(), ResultsClient()
    if attribute is not None:
        setattr(client1, attribute, value)
        setattr(client2, attribute, value)
    events = []
    plain, _, summary_plain, row_plain = run(tmp_path / "plain", client1)
    traced, before, summary_traced, row_traced = run(
        tmp_path / "trace", client2, events.append,
    )
    assert summary_traced == summary_plain
    for field in (
        "status", "stake_nok", "gross_return_nok", "net_pnl_nok",
        "closing_price", "clv", "selections_json", "available_price",
    ):
        assert row_traced[field] == row_plain[field]
    assert before["stake_nok"] == 25.0
    assert len(events) == 1
    assert events[0]["decision_reason"] == expected_reason
    assert events[0]["eligibility"] == (
        "ACCEPTED" if expected_reason == "SETTLED" else "REJECTED"
    )
    assert events[0]["source_raw_body_retained_by_settlement"] is False
    assert events[0]["bet_authority"] is False
    assert traced.count("shadow_tickets") == plain.count("shadow_tickets") == 1


def test_repeated_pending_run_creates_distinct_attempts_but_no_extra_tickets(tmp_path):
    store = _store(tmp_path)
    ticket(store)
    client = ResultsClient()
    client.finish = 0
    events = []
    assert settle_open_shadow_tickets(store, client=client, trace_hook=events.append).pending == 1
    assert settle_open_shadow_tickets(store, client=client, trace_hook=events.append).pending == 1
    assert len(events) == 2
    assert len({e["attempt_id"] for e in events}) == 2
    assert store.count("shadow_tickets") == 1


def test_successful_second_settlement_run_does_not_emit_duplicate(tmp_path):
    store = _store(tmp_path)
    ticket(store)
    events = []
    assert settle_open_shadow_tickets(store, client=ResultsClient(), trace_hook=events.append).settled == 1
    assert settle_open_shadow_tickets(store, client=ResultsClient(), trace_hook=events.append).attempted == 0
    assert len(events) == 1
    assert store.fetch_table("shadow_tickets")[0]["status"] == "SETTLED"


def test_observer_error_does_not_change_settlement(tmp_path):
    def exploding_observer(_event):
        raise RuntimeError("SIMULATED_JOURNAL_DISK_UNAVAILABLE")
    store, _, summary, row = run(tmp_path, ResultsClient(), exploding_observer)
    assert summary.settled == 1
    assert row["status"] == "SETTLED"
    assert row["net_pnl_nok"] == -25.0
    assert store.count("shadow_tickets") == 1


def test_explicit_private_journal_readback_and_write_once(tmp_path):
    folder = tmp_path / "private"
    folder.mkdir(mode=0o700)
    _, _, summary, _ = run(tmp_path / "state", PublicClient())
    assert summary.settled == 1
    # No trace was generated by the previous call.
    assert not list(folder.iterdir())
    trace = []
    run(tmp_path / "new", PublicClient(), trace.append)
    journal = PrivateAttemptJournal(folder)
    journal(trace[0])
    verified = verify_trace(folder, trace[0]["attempt_id"])
    assert verified["readback_sha256_verified"] is True
    assert verified["independently_signed_or_immutable"] is False
    with pytest.raises(FileExistsError):
        journal(trace[0])
    body = folder / (trace[0]["attempt_id"] + ".json")
    body.write_bytes(body.read_bytes() + b"x")
    with pytest.raises(PrivateTraceRejected, match="SHA256"):
        verify_trace(folder, trace[0]["attempt_id"])


def test_private_trace_root_must_be_owned_private(tmp_path):
    folder = tmp_path / "public"
    folder.mkdir(mode=0o755)
    with pytest.raises(PrivateTraceRejected, match="0700"):
        PrivateAttemptJournal(folder)


def test_disqualification_positive_participation_is_settled_without_trace_decision_change(tmp_path):
    events = []
